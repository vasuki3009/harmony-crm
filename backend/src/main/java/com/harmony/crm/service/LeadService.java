package com.harmony.crm.service;

import com.harmony.crm.domain.Lead;
import com.harmony.crm.domain.LeadActivity;
import com.harmony.crm.enums.ActivityType;
import com.harmony.crm.enums.LeadStatus;
import com.harmony.crm.enums.LeadTemperature;
import com.harmony.crm.exception.ResourceNotFoundException;
import com.harmony.crm.repository.LeadActivityRepository;
import com.harmony.crm.repository.LeadRepository;
import com.harmony.crm.repository.LeadSpecifications;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;

@Service
@Transactional
public class LeadService {

    private final LeadRepository leads;
    private final LeadActivityRepository activities;
    private final UserService userService;
    private final PatchHelper patcher;

    public LeadService(LeadRepository leads, LeadActivityRepository activities,
                       UserService userService, PatchHelper patcher) {
        this.leads = leads;
        this.activities = activities;
        this.userService = userService;
        this.patcher = patcher;
    }

    @Transactional(readOnly = true)
    public List<Lead> list(LeadStatus status, LeadTemperature temperature, String assignedTo, String q) {
        return leads.findAll(LeadSpecifications.filter(status, temperature, assignedTo, q),
                Sort.by(Sort.Direction.DESC, "createdAt"));
    }

    @Transactional(readOnly = true)
    public Lead get(String id) {
        return leads.findById(id).orElseThrow(() -> new ResourceNotFoundException("Lead", id));
    }

    public Lead create(Lead lead) {
        lead.setId(null);                       // ids are always generated by the server
        LocalDate today = LocalDate.now();
        lead.setCreatedAt(today);
        lead.setUpdatedAt(today);
        Lead saved = leads.save(lead);
        addActivity(saved.getId(), ActivityType.NOTE, "Lead created");
        return saved;
    }

    /** Partial update. A status change is automatically written to the activity timeline. */
    public Lead patch(String id, Map<String, Object> body) {
        Lead lead = get(id);
        LeadStatus before = lead.getStatus();
        patcher.apply(lead, body, "createdAt", "updatedAt");
        lead.setUpdatedAt(LocalDate.now());
        Lead saved = leads.save(lead);
        if (before != saved.getStatus()) {
            addActivity(id, ActivityType.STATUS_CHANGE,
                    "Status changed: " + label(before) + " → " + label(saved.getStatus()));
        }
        return saved;
    }

    public void delete(String id) {
        Lead lead = get(id);
        activities.deleteByLeadId(id);
        leads.delete(lead);
    }

    @Transactional(readOnly = true)
    public List<LeadActivity> activities(String leadId) {
        get(leadId);   // 404 if the lead does not exist
        return activities.findByLeadIdOrderByCreatedAtDesc(leadId);
    }

    public LeadActivity addActivity(String leadId, ActivityType type, String description) {
        get(leadId);
        LeadActivity activity = LeadActivity.builder()
                .leadId(leadId)
                .type(type)
                .description(description)
                .performedBy(userService.currentUser().getId())
                .createdAt(LocalDateTime.now())
                .build();
        return activities.save(activity);
    }

    private static String label(LeadStatus status) {
        String lower = status.name().toLowerCase();
        return Character.toUpperCase(lower.charAt(0)) + lower.substring(1);
    }
}
